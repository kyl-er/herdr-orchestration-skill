#!/usr/bin/env bash
# Rebuild reference/commands.md from the installed herdr binary, then regenerate AGENTS.md.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
SKILL="$ROOT/herdr-orchestration"
bash "$SKILL/bin/gen-herdr-command-index.sh" "$SKILL/reference/commands.md"

OUT="$ROOT/AGENTS.md"
{
  echo "# AGENTS.md — herdr orchestration"
  echo
  echo "> Context for any coding agent (Claude Code, Codex, OpenCode, Hermes, pi, etc.) that needs to"
  echo "> drive **herdr** to run and coordinate other agents. Generated by \`build.sh\` from"
  echo "> \`herdr-orchestration/SKILL.md\` + \`reference/commands.md\`. Do not hand-edit — edit the sources and rebuild."
  echo
  echo "Files in this repo:"
  echo
  echo "- \`herdr-orchestration/SKILL.md\` — the skill (Claude Code / Agent Skills format)"
  echo "- \`herdr-orchestration/reference/commands.md\` — full CLI help dump, generated from the binary"
  echo "- \`herdr-orchestration/reference/states-and-comms.md\` — deep reference: state detection, push/pull channels, comms levels"
  echo "- \`herdr-orchestration/bin/gen-herdr-command-index.sh\` — regenerates the command index"
  echo
  echo "---"
  echo
  awk 'BEGIN{fm=0} /^---$/ && fm<2 {fm++; next} fm>=2' "$SKILL/SKILL.md" | sed 's/^# herdr orchestration/## Skill: herdr orchestration/'
  echo
  echo "---"
  echo
  echo "## CLI command index"
  echo
  echo "One line per command, grouped. $(grep -m1 'version:' "$SKILL/reference/commands.md" | sed 's/^- //')."
  echo "Full help text: \`herdr-orchestration/reference/commands.md\`. The installed binary is always the authority —"
  echo "run \`herdr <group>\` with no subcommand to print current syntax. **Never run bare \`herdr\`** (launches the TUI)."
  echo
  echo "### Top level"
  echo
  echo '```'
  sed -n '/^Common commands:/,/^Options:/p' "$SKILL/reference/commands.md" | grep -E '^  herdr' | sed 's/^  //'
  echo '```'
  awk '
    /^## herdr / { if (open) print "```"; g=$3; print ""; print "### herdr " g; print ""; print "```"; open=1; next }
    open && /^  herdr / { sub(/^  /,""); print; next }
    open && /^  (targets|kinds|use )/ { sub(/^  /,"# "); print }
    END { if (open) print "```" }
  ' "$SKILL/reference/commands.md"
  echo
  echo "---"
  echo
  echo "## Dispatcher cheat-sheet"
  echo
  sed -n '/^## 5. Dispatcher cheat-sheet/,$p' "$SKILL/reference/states-and-comms.md" | tail -n +3
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
